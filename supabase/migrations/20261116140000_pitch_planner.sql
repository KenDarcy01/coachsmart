-- Pitch planner for club admins (Ken approved 2026-11-16, thread "Plan pitch
-- allocation portal for club admins"). Additive only: new tables plus
-- SECURITY DEFINER functions that check the caller is a pitch admin of the
-- club. Used by the v3 Pitches page; v2 never reads these tables.
--
-- Times: bookings store the local (Irish) wall-clock time as `timestamp`
-- without a zone, the same clock events.event_date_time and
-- gaa_games.start_at hold (both are local time labelled +00).

-- ---------------------------------------------------------------- tables

CREATE TABLE IF NOT EXISTS public.pitch_venues (
  venue_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id      bigint NOT NULL REFERENCES public.clubs(club_id) ON DELETE CASCADE,
  name         text   NOT NULL,
  address      text,
  location_pin text,
  rented       boolean NOT NULL DEFAULT false,
  sort         int NOT NULL DEFAULT 0,
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pitch_venues_club_idx ON public.pitch_venues(club_id);

CREATE TABLE IF NOT EXISTS public.pitches (
  pitch_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id   bigint NOT NULL REFERENCES public.pitch_venues(venue_id) ON DELETE CASCADE,
  club_id    bigint NOT NULL REFERENCES public.clubs(club_id) ON DELETE CASCADE,
  name       text   NOT NULL,
  surface    text   NOT NULL DEFAULT 'grass'
             CHECK (surface IN ('grass','astro','indoor','other')),
  floodlit   boolean NOT NULL DEFAULT false,
  split      smallint NOT NULL DEFAULT 1 CHECK (split IN (1,2,4)),
  aliases    text[] NOT NULL DEFAULT '{}',
  sort       int NOT NULL DEFAULT 0,
  is_active  boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pitches_club_idx ON public.pitches(club_id);

-- Weekly opening hours (weekday 1 = Monday ... 7 = Sunday). No rows = open
-- 08:00-22:00 every day.
CREATE TABLE IF NOT EXISTS public.pitch_hours (
  hour_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pitch_id bigint NOT NULL REFERENCES public.pitches(pitch_id) ON DELETE CASCADE,
  weekday  smallint NOT NULL CHECK (weekday BETWEEN 1 AND 7),
  opens    time NOT NULL,
  closes   time NOT NULL CHECK (closes > opens)
);
CREATE INDEX IF NOT EXISTS pitch_hours_pitch_idx ON public.pitch_hours(pitch_id);

CREATE TABLE IF NOT EXISTS public.pitch_closures (
  closure_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pitch_id   bigint NOT NULL REFERENCES public.pitches(pitch_id) ON DELETE CASCADE,
  starts_on  date NOT NULL,
  ends_on    date NOT NULL CHECK (ends_on >= starts_on),
  reason     text,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pitch_closures_pitch_idx ON public.pitch_closures(pitch_id, starts_on);

-- One row per use of a pitch. part is a bit mask of quarters (1,2 = left
-- half, 4,8 = right half, 15 = full pitch), so two bookings clash when their
-- times overlap and (part_a & part_b) <> 0.
-- status: confirmed (on the pitch), requested (a coach asked), offsite
-- (admin marked it "not on our pitches", pitch_id is null).
CREATE TABLE IF NOT EXISTS public.pitch_bookings (
  booking_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id       bigint NOT NULL REFERENCES public.clubs(club_id) ON DELETE CASCADE,
  pitch_id      bigint REFERENCES public.pitches(pitch_id) ON DELETE CASCADE,
  part          smallint NOT NULL DEFAULT 15 CHECK (part BETWEEN 1 AND 15),
  starts_at     timestamp NOT NULL,
  ends_at       timestamp NOT NULL CHECK (ends_at > starts_at),
  kind          text NOT NULL DEFAULT 'training'
                CHECK (kind IN ('match','training','other')),
  title         text,
  team_id       bigint REFERENCES public.teams(team_id) ON DELETE SET NULL,
  event_id      bigint REFERENCES public.events(event_id) ON DELETE CASCADE,
  gaa_game_id   bigint,
  status        text NOT NULL DEFAULT 'confirmed'
                CHECK (status IN ('confirmed','requested','offsite')),
  note          text,
  prev_location text,
  prev_pin      text,
  created_by    uuid,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (status = 'offsite' OR pitch_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS pitch_bookings_event_uq ON public.pitch_bookings(event_id) WHERE event_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS pitch_bookings_game_uq ON public.pitch_bookings(club_id, gaa_game_id) WHERE gaa_game_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS pitch_bookings_club_time_idx ON public.pitch_bookings(club_id, starts_at);

-- Default slot lengths in minutes (they include warm-up and half time);
-- changeover is the gap the board wants between two uses of a pitch.
CREATE TABLE IF NOT EXISTS public.pitch_club_settings (
  club_id    bigint PRIMARY KEY REFERENCES public.clubs(club_id) ON DELETE CASCADE,
  durations  jsonb NOT NULL DEFAULT
    '{"u12":50,"u16":60,"adult":90,"training":60,"other":60,"changeover":15}',
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.pitch_venues        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pitches             ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pitch_hours         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pitch_closures      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pitch_bookings      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pitch_club_settings ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------- helpers

CREATE OR REPLACE FUNCTION public.pitch_norm(t text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path = 'public' AS $$
  SELECT regexp_replace(lower(coalesce(t, '')), '[^a-z0-9]', '', 'g');
$$;

-- Access is the club officer role (club_officers, owned by thread "Build
-- club chairperson dashboard"): an active officer of the club or any
-- SuperUser. plpgsql so this file does not depend on load order.
CREATE OR REPLACE FUNCTION public.is_club_pitch_admin(p_club bigint)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
BEGIN
  RETURN auth.uid() IS NOT NULL AND coalesce(public.is_club_officer(p_club), false);
END $$;

CREATE OR REPLACE FUNCTION public.pitch_require_admin(p_club bigint)
RETURNS void LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
BEGIN
  IF NOT coalesce(public.is_club_pitch_admin(p_club), false) THEN
    RAISE EXCEPTION 'Only club admins can use the pitch planner' USING ERRCODE = '42501';
  END IF;
END $$;

-- Pitch whose name or "also called" names match a free-text location.
CREATE OR REPLACE FUNCTION public.pitch_match(p_club bigint, p_text text)
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
  SELECT p.pitch_id
    FROM pitches p
   WHERE p.club_id = p_club AND p.is_active
     AND public.pitch_norm(p_text) <> ''
     AND (public.pitch_norm(p.name) = public.pitch_norm(p_text)
          OR EXISTS (SELECT 1 FROM unnest(p.aliases) a
                      WHERE public.pitch_norm(a) = public.pitch_norm(p_text)))
   ORDER BY p.sort, p.pitch_id
   LIMIT 1;
$$;

