CREATE OR REPLACE FUNCTION public.pitch_setup(p_club bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE r jsonb;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  SELECT jsonb_build_object(
    'durations', coalesce((SELECT durations FROM pitch_club_settings WHERE club_id = p_club),
        '{"u12":50,"u16":60,"adult":90,"training":60,"other":60,"changeover":15}'::jsonb),
    'venues', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
               'venue_id', v.venue_id, 'name', v.name, 'address', v.address,
               'location_pin', v.location_pin, 'rented', v.rented, 'sort', v.sort,
               'pitches', coalesce((
                 SELECT jsonb_agg(jsonb_build_object(
                          'pitch_id', p.pitch_id, 'venue_id', p.venue_id, 'name', p.name,
                          'surface', p.surface, 'floodlit', p.floodlit, 'split', p.split,
                          'aliases', to_jsonb(p.aliases), 'sort', p.sort,
                          'hours', coalesce((SELECT jsonb_agg(jsonb_build_object(
                                     'weekday', h.weekday, 'opens', to_char(h.opens, 'HH24:MI'),
                                     'closes', to_char(h.closes, 'HH24:MI')) ORDER BY h.weekday, h.opens)
                                     FROM pitch_hours h WHERE h.pitch_id = p.pitch_id), '[]'::jsonb))
                        ORDER BY p.sort, p.pitch_id)
                   FROM pitches p WHERE p.venue_id = v.venue_id AND p.is_active), '[]'::jsonb))
             ORDER BY v.sort, v.venue_id)
        FROM pitch_venues v WHERE v.club_id = p_club AND v.is_active), '[]'::jsonb),
    -- Event locations (last 120 days, next 60) that match no pitch yet.
    'unmatched', coalesce((
      SELECT jsonb_agg(jsonb_build_object('location', x.loc, 'events', x.n) ORDER BY x.n DESC)
        FROM (SELECT min(trim(e.location_name)) AS loc, count(*) AS n
                FROM events e JOIN teams t ON t.team_id = e.team_id
               WHERE t.club_id = p_club
                 AND e.event_date_time BETWEEN now() - interval '120 days' AND now() + interval '60 days'
                 AND public.pitch_norm(e.location_name) <> ''
                 AND coalesce(e.home_away, '') <> 'Away'
                 AND public.pitch_match(p_club, e.location_name) IS NULL
               GROUP BY public.pitch_norm(e.location_name)
               ORDER BY count(*) DESC
               LIMIT 25) x), '[]'::jsonb))
  INTO r;
  RETURN r;
END $$;

-- Everything the board needs for a range of days (local dates, inclusive).
CREATE OR REPLACE FUNCTION public.pitch_board(p_club bigint, p_from date, p_to date)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  r jsonb;
  v_gaa int;
  v_from timestamp := p_from::timestamp;
  v_to   timestamp := (p_to + 1)::timestamp;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  IF p_to < p_from OR p_to - p_from > 62 THEN
    RAISE EXCEPTION 'Pick up to 9 weeks at a time';
  END IF;
  SELECT gaa_club_id INTO v_gaa FROM clubs WHERE club_id = p_club;

  WITH ev AS (
    SELECT e.event_id, e.team_id, t.team_name, e.event_title, e.opposition, e.home_away,
           e.location_name, e.status, et.event_type,
           (e.event_date_time AT TIME ZONE 'UTC') AS starts_at
      FROM events e
      JOIN teams t ON t.team_id = e.team_id
      LEFT JOIN event_types et ON et.event_type_id = e.event_type_id
     WHERE t.club_id = p_club
       AND (e.event_date_time AT TIME ZONE 'UTC') >= v_from
       AND (e.event_date_time AT TIME ZONE 'UTC') <  v_to
  ), gm AS (
    SELECT g.game_id, g.code, g.home_team, g.away_team, g.venue, g.status,
           (g.start_at AT TIME ZONE 'UTC') AS starts_at, gc.age, gc.name AS comp_name
      FROM gaa_games g
      LEFT JOIN gaa_competitions gc ON gc.comp_id = g.comp_id
     WHERE v_gaa IS NOT NULL AND g.home_club_id = v_gaa
       AND (g.start_at AT TIME ZONE 'UTC') >= v_from
       AND (g.start_at AT TIME ZONE 'UTC') <  v_to
       AND lower(coalesce(g.away_team, '')) NOT IN ('', 'bye')
  )
  SELECT jsonb_build_object(
    'durations', coalesce((SELECT durations FROM pitch_club_settings WHERE club_id = p_club),
        '{"u12":50,"u16":60,"adult":90,"training":60,"other":60,"changeover":15}'::jsonb),
    'pitches', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
               'pitch_id', p.pitch_id, 'venue_id', p.venue_id, 'venue', v.name,
               'venue_pin', v.location_pin, 'rented', v.rented,
               'name', p.name, 'surface', p.surface, 'floodlit', p.floodlit, 'split', p.split,
               'hours', coalesce((SELECT jsonb_agg(jsonb_build_object(
                          'weekday', h.weekday, 'opens', to_char(h.opens, 'HH24:MI'),
                          'closes', to_char(h.closes, 'HH24:MI')) ORDER BY h.weekday, h.opens)
                          FROM pitch_hours h WHERE h.pitch_id = p.pitch_id), '[]'::jsonb))
             ORDER BY v.sort, v.venue_id, p.sort, p.pitch_id)
        FROM pitches p JOIN pitch_venues v ON v.venue_id = p.venue_id
       WHERE p.club_id = p_club AND p.is_active AND v.is_active), '[]'::jsonb),
    'closures', coalesce((
      SELECT jsonb_agg(jsonb_build_object('closure_id', c.closure_id, 'pitch_id', c.pitch_id,
               'starts_on', c.starts_on, 'ends_on', c.ends_on, 'reason', c.reason))
        FROM pitch_closures c JOIN pitches p ON p.pitch_id = c.pitch_id
       WHERE p.club_id = p_club AND c.starts_on <= p_to AND c.ends_on >= p_from), '[]'::jsonb),
    'bookings', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
               'booking_id', b.booking_id, 'pitch_id', b.pitch_id, 'part', b.part,
               'starts_at', to_char(b.starts_at, 'YYYY-MM-DD"T"HH24:MI:SS'),
               'ends_at', to_char(b.ends_at, 'YYYY-MM-DD"T"HH24:MI:SS'),
               'kind', b.kind, 'title', b.title, 'team_id', b.team_id, 'team_name', t.team_name,
               'event_id', b.event_id, 'gaa_game_id', b.gaa_game_id, 'status', b.status,
               'note', b.note, 'event_status', e.status, 'code', g.code)
             ORDER BY b.starts_at)
        FROM pitch_bookings b
        LEFT JOIN teams t ON t.team_id = b.team_id
        LEFT JOIN events e ON e.event_id = b.event_id
        LEFT JOIN gaa_games g ON g.game_id = b.gaa_game_id
       WHERE b.club_id = p_club AND b.starts_at < v_to AND b.ends_at > v_from), '[]'::jsonb),
    -- Events with no booking: matched_pitch_id is the pitch their location
    -- names (if any). Away matches are left out.
    'events', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
               'event_id', ev.event_id, 'team_id', ev.team_id, 'team_name', ev.team_name,
               'title', ev.event_title, 'opposition', ev.opposition, 'home_away', ev.home_away,
               'location', ev.location_name, 'status', ev.status, 'type', ev.event_type,
               'starts_at', to_char(ev.starts_at, 'YYYY-MM-DD"T"HH24:MI:SS'),
               'matched_pitch_id', public.pitch_match(p_club, ev.location_name))
             ORDER BY ev.starts_at)
        FROM ev
       WHERE coalesce(ev.home_away, '') <> 'Away'
         AND coalesce(ev.status, '') NOT ILIKE 'cancel%'
         AND NOT EXISTS (SELECT 1 FROM pitch_bookings b WHERE b.event_id = ev.event_id)), '[]'::jsonb),
    -- Home league fixtures not booked and not already a CoachSmart match
    -- event within 90 minutes against the same opposition.
    'fixtures', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
               'game_id', gm.game_id, 'code', gm.code, 'age', gm.age, 'comp', gm.comp_name,
               'home', gm.home_team, 'away', gm.away_team, 'venue', gm.venue, 'status', gm.status,
               'starts_at', to_char(gm.starts_at, 'YYYY-MM-DD"T"HH24:MI:SS'),
               'matched_pitch_id', public.pitch_match(p_club, gm.venue))
             ORDER BY gm.starts_at)
        FROM gm
       WHERE NOT EXISTS (SELECT 1 FROM pitch_bookings b
                          WHERE b.club_id = p_club AND b.gaa_game_id = gm.game_id)
         AND NOT EXISTS (SELECT 1 FROM ev
                          WHERE abs(extract(epoch FROM ev.starts_at - gm.starts_at)) <= 5400
                            AND coalesce(ev.opposition, '') <> ''
                            AND (public.pitch_norm(ev.opposition) LIKE '%' || public.pitch_norm(split_part(gm.away_team, ' ', 1)) || '%'
                                 OR public.pitch_norm(gm.away_team) LIKE '%' || public.pitch_norm(ev.opposition) || '%'))), '[]'::jsonb)
  ) INTO r;
  RETURN r;
END $$;

