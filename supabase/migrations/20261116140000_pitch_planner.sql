CREATE OR REPLACE FUNCTION public.pitch_venue_save(p_club bigint, p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE v_id bigint := nullif(p->>'venue_id', '')::bigint;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  IF coalesce(trim(p->>'name'), '') = '' THEN RAISE EXCEPTION 'Give the venue a name'; END IF;
  IF v_id IS NULL THEN
    INSERT INTO pitch_venues(club_id, name, address, location_pin, rented, sort)
    VALUES (p_club, trim(p->>'name'), nullif(trim(p->>'address'), ''), nullif(trim(p->>'location_pin'), ''),
            coalesce((p->>'rented')::boolean, false),
            coalesce((p->>'sort')::int, (SELECT coalesce(max(sort), 0) + 1 FROM pitch_venues WHERE club_id = p_club)))
    RETURNING venue_id INTO v_id;
  ELSE
    UPDATE pitch_venues SET name = trim(p->>'name'), address = nullif(trim(p->>'address'), ''),
           location_pin = nullif(trim(p->>'location_pin'), ''),
           rented = coalesce((p->>'rented')::boolean, rented),
           sort = coalesce((p->>'sort')::int, sort),
           is_active = coalesce((p->>'is_active')::boolean, is_active)
     WHERE venue_id = v_id AND club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Venue not found'; END IF;
  END IF;
  RETURN v_id;
END $$;

CREATE OR REPLACE FUNCTION public.pitch_save(p_club bigint, p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  v_id bigint := nullif(p->>'pitch_id', '')::bigint;
  v_venue bigint := (p->>'venue_id')::bigint;
  v_aliases text[];
  h jsonb;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  IF NOT EXISTS (SELECT 1 FROM pitch_venues WHERE venue_id = v_venue AND club_id = p_club) THEN
    RAISE EXCEPTION 'Venue not found';
  END IF;
  IF coalesce(trim(p->>'name'), '') = '' THEN RAISE EXCEPTION 'Give the pitch a name'; END IF;
  SELECT coalesce(array_agg(DISTINCT trim(a)) FILTER (WHERE trim(a) <> ''), '{}')
    INTO v_aliases FROM jsonb_array_elements_text(coalesce(p->'aliases', '[]'::jsonb)) a;

  IF v_id IS NULL THEN
    INSERT INTO pitches(venue_id, club_id, name, surface, floodlit, split, aliases, sort)
    VALUES (v_venue, p_club, trim(p->>'name'), coalesce(p->>'surface', 'grass'),
            coalesce((p->>'floodlit')::boolean, false), coalesce((p->>'split')::smallint, 1), v_aliases,
            coalesce((p->>'sort')::int, (SELECT coalesce(max(sort), 0) + 1 FROM pitches WHERE venue_id = v_venue)))
    RETURNING pitch_id INTO v_id;
  ELSE
    UPDATE pitches SET venue_id = v_venue, name = trim(p->>'name'),
           surface = coalesce(p->>'surface', surface),
           floodlit = coalesce((p->>'floodlit')::boolean, floodlit),
           split = coalesce((p->>'split')::smallint, split),
           aliases = CASE WHEN p ? 'aliases' THEN v_aliases ELSE aliases END,
           sort = coalesce((p->>'sort')::int, sort),
           is_active = coalesce((p->>'is_active')::boolean, is_active)
     WHERE pitch_id = v_id AND club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Pitch not found'; END IF;
  END IF;

  IF p ? 'hours' THEN
    DELETE FROM pitch_hours WHERE pitch_id = v_id;
    FOR h IN SELECT * FROM jsonb_array_elements(coalesce(p->'hours', '[]'::jsonb)) LOOP
      INSERT INTO pitch_hours(pitch_id, weekday, opens, closes)
      VALUES (v_id, (h->>'weekday')::smallint, (h->>'opens')::time, (h->>'closes')::time);
    END LOOP;
  END IF;
  RETURN v_id;
END $$;

CREATE OR REPLACE FUNCTION public.pitch_settings_save(p_club bigint, p_durations jsonb)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  INSERT INTO pitch_club_settings(club_id, durations, updated_at)
  VALUES (p_club, p_durations, now())
  ON CONFLICT (club_id) DO UPDATE SET durations = excluded.durations, updated_at = now();
END $$;

CREATE OR REPLACE FUNCTION public.pitch_closure_save(p_club bigint, p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE v_id bigint;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  IF NOT EXISTS (SELECT 1 FROM pitches WHERE pitch_id = (p->>'pitch_id')::bigint AND club_id = p_club) THEN
    RAISE EXCEPTION 'Pitch not found';
  END IF;
  INSERT INTO pitch_closures(pitch_id, starts_on, ends_on, reason, created_by)
  VALUES ((p->>'pitch_id')::bigint, (p->>'starts_on')::date,
          coalesce((p->>'ends_on')::date, (p->>'starts_on')::date),
          nullif(trim(p->>'reason'), ''), auth.uid())
  RETURNING closure_id INTO v_id;
  RETURN v_id;
END $$;

CREATE OR REPLACE FUNCTION public.pitch_closure_delete(p_club bigint, p_closure bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  DELETE FROM pitch_closures c USING pitches p
   WHERE c.closure_id = p_closure AND p.pitch_id = c.pitch_id AND p.club_id = p_club;
END $$;

-- Save a booking. For a CoachSmart event the pitch also goes onto the
-- event's location (Ken OK'd, 2026-11-16); the old location is kept on the
-- booking and put back if the booking is removed.
CREATE OR REPLACE FUNCTION public.pitch_booking_save(p_club bigint, p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  v_id     bigint := nullif(p->>'booking_id', '')::bigint;
  v_pitch  bigint := nullif(p->>'pitch_id', '')::bigint;
  v_event  bigint := nullif(p->>'event_id', '')::bigint;
  v_game   bigint := nullif(p->>'gaa_game_id', '')::bigint;
  v_team   bigint := nullif(p->>'team_id', '')::bigint;
  v_status text   := coalesce(nullif(p->>'status', ''), 'confirmed');
  v_part   smallint := coalesce((p->>'part')::smallint, 15);
  v_split  smallint;
  v_loc    text;
  v_pin    text;
  v_old    pitch_bookings%ROWTYPE;
BEGIN
  PERFORM public.pitch_require_admin(p_club);

  IF v_id IS NOT NULL THEN
    SELECT * INTO v_old FROM pitch_bookings WHERE booking_id = v_id AND club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found'; END IF;
    v_event := coalesce(v_event, v_old.event_id);
    v_game  := coalesce(v_game, v_old.gaa_game_id);
  END IF;

  IF v_status <> 'offsite' THEN
    SELECT p2.split, p2.name || ', ' || v.name, v.location_pin INTO v_split, v_loc, v_pin
      FROM pitches p2 JOIN pitch_venues v ON v.venue_id = p2.venue_id
     WHERE p2.pitch_id = v_pitch AND p2.club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Pitch not found'; END IF;
    IF v_split = 1 THEN v_part := 15;
    ELSIF v_split = 2 AND v_part NOT IN (3, 12, 15) THEN v_part := 15;
    END IF;
  ELSE
    v_pitch := NULL; v_part := 15;
  END IF;

  IF v_event IS NOT NULL THEN
    SELECT e.team_id INTO v_team FROM events e JOIN teams t ON t.team_id = e.team_id
     WHERE e.event_id = v_event AND t.club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Event not found'; END IF;
  ELSIF v_team IS NOT NULL AND NOT EXISTS (SELECT 1 FROM teams WHERE team_id = v_team AND club_id = p_club) THEN
    RAISE EXCEPTION 'Team not found';
  END IF;
  IF v_game IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM gaa_games g JOIN clubs c ON c.gaa_club_id = g.home_club_id
        WHERE g.game_id = v_game AND c.club_id = p_club) THEN
    RAISE EXCEPTION 'Fixture not found';
  END IF;

  IF v_id IS NULL THEN
    INSERT INTO pitch_bookings(club_id, pitch_id, part, starts_at, ends_at, kind, title, team_id,
                               event_id, gaa_game_id, status, note, created_by)
    VALUES (p_club, v_pitch, v_part, (p->>'starts_at')::timestamp, (p->>'ends_at')::timestamp,
            coalesce(nullif(p->>'kind', ''), 'training'), nullif(trim(p->>'title'), ''), v_team,
            v_event, v_game, v_status, nullif(trim(p->>'note'), ''), auth.uid())
    RETURNING booking_id INTO v_id;
  ELSE
    UPDATE pitch_bookings SET pitch_id = v_pitch, part = v_part,
           starts_at = coalesce((p->>'starts_at')::timestamp, starts_at),
           ends_at = coalesce((p->>'ends_at')::timestamp, ends_at),
           kind = coalesce(nullif(p->>'kind', ''), kind),
           title = CASE WHEN p ? 'title' THEN nullif(trim(p->>'title'), '') ELSE title END,
           team_id = v_team, status = v_status,
           note = CASE WHEN p ? 'note' THEN nullif(trim(p->>'note'), '') ELSE note END,
           updated_at = now()
     WHERE booking_id = v_id;
  END IF;

  IF v_event IS NOT NULL THEN
    -- Remember what the coach had, once.
    UPDATE pitch_bookings b SET prev_location = e.location_name, prev_pin = e.location_pin
      FROM events e
     WHERE b.booking_id = v_id AND e.event_id = v_event AND b.prev_location IS NULL AND b.prev_pin IS NULL
       AND (v_old.booking_id IS NULL);
    IF v_status = 'confirmed' THEN
      UPDATE events SET location_name = v_loc,
             location_pin = coalesce(v_pin, location_pin)
       WHERE event_id = v_event;
    END IF;
  END IF;
  RETURN v_id;
END $$;

CREATE OR REPLACE FUNCTION public.pitch_booking_delete(p_club bigint, p_booking bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE b pitch_bookings%ROWTYPE;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  DELETE FROM pitch_bookings WHERE booking_id = p_booking AND club_id = p_club RETURNING * INTO b;
  IF b.event_id IS NOT NULL AND b.status = 'confirmed'
     AND (b.prev_location IS NOT NULL OR b.prev_pin IS NOT NULL) THEN
    UPDATE events SET location_name = b.prev_location, location_pin = b.prev_pin
     WHERE event_id = b.event_id;
  END IF;
END $$;

