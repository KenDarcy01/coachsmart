-- Important messages (pop-up on app open) and News (top bar on Home), v3 only
-- (Ken, 2026-11-14). Super users only send for now, while testing.
-- Additive: two new tables and new functions. v2 never reads them.
--
-- A message reaches: the chosen teams; or, with no teams, every team of the
-- chosen club; or, with neither, every CoachSmart user. audience narrows it to
-- players and parents (role level under 30) or coaches and admins (30+).
-- Important: shown on each open until the user dismisses it (X or Got it).
-- News: shown in the bar until ends_at; seen_at only drives the unread dot.

CREATE TABLE IF NOT EXISTS public.app_messages (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind           text NOT NULL CHECK (kind IN ('important', 'news')),
  title          text NOT NULL,
  body           text NOT NULL DEFAULT '',
  link_url       text,
  link_label     text,
  sender_user_id uuid NOT NULL REFERENCES public.users(user_id),
  club_id        bigint REFERENCES public.clubs(club_id),
  team_ids       bigint[] NOT NULL DEFAULT '{}',
  audience       text NOT NULL DEFAULT 'all'
                 CHECK (audience IN ('all', 'players', 'staff')),
  starts_at      timestamptz NOT NULL DEFAULT now(),
  ends_at        timestamptz NOT NULL,
  ended_at       timestamptz,   -- stopped early by the sender
  deleted_at     timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.app_message_reads (
  message_id   bigint NOT NULL REFERENCES public.app_messages(id) ON DELETE CASCADE,
  user_id      uuid NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  seen_at      timestamptz NOT NULL DEFAULT now(),
  dismissed_at timestamptz,
  PRIMARY KEY (message_id, user_id)
);

-- Only the functions below touch these tables.
ALTER TABLE public.app_messages      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_message_reads ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.app_messages, public.app_message_reads FROM anon, authenticated;

-- ---------------------------------------------------------------------------
-- SuperUser (role level 110) on any active team, as on the v3 Team page.
CREATE OR REPLACE FUNCTION public.is_app_super_user()
 RETURNS boolean
 LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $$
  SELECT auth.uid() IS NOT NULL AND EXISTS (
    SELECT 1
      FROM members m
      JOIN member_team_link mtl       ON mtl.member_id = m.member_id
      JOIN member_team_role_link mtrl ON mtrl.member_team_id = mtl.member_team_id
      JOIN roles r                    ON r.role_id = mtrl.role_id
     WHERE m.user_id = auth.uid()
       AND mtl.status = 'active'
       AND r.role_level >= 110);
$$;

-- The users a message reaches (p_user narrows it to one user).
CREATE OR REPLACE FUNCTION public.app_message_audience(
  p_club_id bigint, p_team_ids bigint[], p_audience text, p_user uuid DEFAULT NULL)
 RETURNS TABLE(user_id uuid)
 LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $$
  SELECT DISTINCT uml.user_id
    FROM user_member_link uml
    JOIN users u            ON u.user_id = uml.user_id AND u.deleted_at IS NULL
    JOIN member_team_link mtl ON mtl.member_id = uml.member_id
                             AND COALESCE(mtl.status, 'active') = 'active'
    JOIN teams t            ON t.team_id = mtl.team_id
   WHERE COALESCE(uml.status, 'active') = 'active'
     AND (p_user IS NULL OR uml.user_id = p_user)
     AND CASE
           WHEN COALESCE(cardinality(p_team_ids), 0) > 0 THEN mtl.team_id = ANY (p_team_ids)
           WHEN p_club_id IS NOT NULL THEN t.club_id = p_club_id
           ELSE true
         END
     AND (COALESCE(p_audience, 'all') = 'all' OR EXISTS (
           SELECT 1
             FROM member_team_role_link mtrl
             JOIN roles r ON r.role_id = mtrl.role_id
            WHERE mtrl.member_team_id = mtl.member_team_id
              AND ((p_audience = 'players' AND r.role_level < 30)
                OR (p_audience = 'staff'   AND r.role_level >= 30))));
$$;
REVOKE ALL ON FUNCTION public.app_message_audience(bigint, bigint[], text, uuid) FROM PUBLIC, anon, authenticated;

-- Who the message says it is from: CoachSmart, the club, or the team.
CREATE OR REPLACE FUNCTION public.app_message_json(m public.app_messages)
 RETURNS jsonb
 LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $$
  SELECT jsonb_build_object(
    'id', m.id, 'kind', m.kind, 'title', m.title, 'body', m.body,
    'link_url', m.link_url, 'link_label', m.link_label,
    'starts_at', m.starts_at, 'ends_at', m.ends_at,
    'scope', CASE WHEN cardinality(m.team_ids) > 0 THEN 'team'
                  WHEN m.club_id IS NOT NULL THEN 'club' ELSE 'all' END,
    'audience', m.audience, 'club_id', m.club_id, 'team_ids', to_jsonb(m.team_ids),
    'from_name', CASE
       WHEN cardinality(m.team_ids) = 1 THEN
         (SELECT c.club_name || ' · ' || t.team_name FROM teams t JOIN clubs c ON c.club_id = t.club_id
           WHERE t.team_id = m.team_ids[1])
       WHEN cardinality(m.team_ids) > 1 THEN
         COALESCE((SELECT c.club_name FROM clubs c WHERE c.club_id = m.club_id), 'Your teams')
       WHEN m.club_id IS NOT NULL THEN (SELECT c.club_name FROM clubs c WHERE c.club_id = m.club_id)
       ELSE 'CoachSmart' END,
    'crest', CASE
       WHEN cardinality(m.team_ids) > 0 THEN
         (SELECT c.crest FROM teams t JOIN clubs c ON c.club_id = t.club_id WHERE t.team_id = m.team_ids[1])
       WHEN m.club_id IS NOT NULL THEN (SELECT c.crest FROM clubs c WHERE c.club_id = m.club_id)
       ELSE NULL END);
$$;
REVOKE ALL ON FUNCTION public.app_message_json(public.app_messages) FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Home: the live messages for the signed-in user.
CREATE OR REPLACE FUNCTION public.get_my_app_messages()
 RETURNS jsonb
 LANGUAGE plpgsql STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_out jsonb;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('important', '[]'::jsonb, 'news', '[]'::jsonb, 'is_super_user', false);
  END IF;

  WITH live AS (
    SELECT m AS msg, r.seen_at, r.dismissed_at
      FROM app_messages m
      LEFT JOIN app_message_reads r ON r.message_id = m.id AND r.user_id = v_uid
     WHERE m.deleted_at IS NULL AND m.ended_at IS NULL
       AND m.starts_at <= now() AND m.ends_at > now()
       AND EXISTS (SELECT 1 FROM app_message_audience(m.club_id, m.team_ids, m.audience, v_uid))
  )
  SELECT jsonb_build_object(
    'is_super_user', is_app_super_user(),
    -- CoachSmart first, then club, then team; newest first within each.
    'important', COALESCE((
       SELECT jsonb_agg(app_message_json(l.msg)
              ORDER BY CASE WHEN cardinality((l.msg).team_ids) > 0 THEN 2
                            WHEN (l.msg).club_id IS NOT NULL THEN 1 ELSE 0 END,
                       (l.msg).starts_at DESC)
         FROM live l WHERE (l.msg).kind = 'important' AND l.dismissed_at IS NULL), '[]'::jsonb),
    'news', COALESCE((
       SELECT jsonb_agg(app_message_json(l.msg)
                        || jsonb_build_object('seen', l.seen_at IS NOT NULL)
              ORDER BY (l.msg).starts_at DESC)
         FROM live l WHERE (l.msg).kind = 'news'), '[]'::jsonb))
    INTO v_out;
  RETURN v_out;
END;
$$;

-- X / Got it on the pop-up.
CREATE OR REPLACE FUNCTION public.dismiss_app_message(p_message_id bigint)
 RETURNS void
 LANGUAGE sql SECURITY DEFINER
 SET search_path TO 'public'
AS $$
  INSERT INTO app_message_reads (message_id, user_id, seen_at, dismissed_at)
  SELECT p_message_id, auth.uid(), now(), now()
   WHERE auth.uid() IS NOT NULL
     AND EXISTS (SELECT 1 FROM app_messages WHERE id = p_message_id)
  ON CONFLICT (message_id, user_id) DO UPDATE SET dismissed_at = now();
$$;

-- News opened in the sheet.
CREATE OR REPLACE FUNCTION public.mark_app_messages_seen(p_message_ids bigint[])
 RETURNS void
 LANGUAGE sql SECURITY DEFINER
 SET search_path TO 'public'
AS $$
  INSERT INTO app_message_reads (message_id, user_id)
  SELECT m.id, auth.uid() FROM app_messages m
   WHERE auth.uid() IS NOT NULL AND m.id = ANY (p_message_ids)
  ON CONFLICT (message_id, user_id) DO NOTHING;
$$;

