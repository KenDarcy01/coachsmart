-- Pitch planner: closure groups (Ken, 2026-11-17). A named set of pitches
-- that usually close together, e.g. the DCC-run St Anne's pitches when they
-- are unplayable. Closing a group writes one pitch_closures row per pitch;
-- each pitch can still be reopened on its own. P34/P35 are run by Clontarf
-- GAA, not DCC, so they are left out of the St Anne's group.

CREATE TABLE IF NOT EXISTS public.pitch_closure_groups (
  group_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id    bigint NOT NULL REFERENCES public.clubs(club_id) ON DELETE CASCADE,
  name       text NOT NULL,
  pitch_ids  bigint[] NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pitch_closure_groups_club_idx ON public.pitch_closure_groups(club_id);
ALTER TABLE public.pitch_closure_groups ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.pitch_closure_groups_get(p_club bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  RETURN coalesce((
    SELECT jsonb_agg(jsonb_build_object('group_id', g.group_id, 'name', g.name,
             'pitch_ids', to_jsonb(g.pitch_ids)) ORDER BY g.name)
      FROM pitch_closure_groups g WHERE g.club_id = p_club), '[]'::jsonb);
END $$;

-- Add (p_group null) or edit a group; pitches of other clubs are dropped.
CREATE OR REPLACE FUNCTION public.pitch_closure_group_save(p_club bigint, p_group bigint,
  p_name text, p_pitches bigint[])
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  v_id bigint := p_group;
  v_pitches bigint[];
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  IF coalesce(trim(p_name), '') = '' THEN RAISE EXCEPTION 'Give the group a name'; END IF;
  SELECT coalesce(array_agg(pitch_id ORDER BY pitch_id), '{}') INTO v_pitches
    FROM pitches WHERE club_id = p_club AND pitch_id = ANY(coalesce(p_pitches, '{}'));
  IF v_id IS NULL THEN
    INSERT INTO pitch_closure_groups(club_id, name, pitch_ids)
    VALUES (p_club, trim(p_name), v_pitches) RETURNING group_id INTO v_id;
  ELSE
    UPDATE pitch_closure_groups SET name = trim(p_name), pitch_ids = v_pitches
     WHERE group_id = v_id AND club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Group not found'; END IF;
  END IF;
  RETURN v_id;
END $$;

CREATE OR REPLACE FUNCTION public.pitch_closure_group_delete(p_club bigint, p_group bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  DELETE FROM pitch_closure_groups WHERE group_id = p_group AND club_id = p_club;
END $$;

-- Close every pitch of a group for the dates; returns how many were closed.
CREATE OR REPLACE FUNCTION public.pitch_closure_group_close(p_club bigint, p_group bigint,
  p_from date, p_to date, p_reason text)
RETURNS int LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE n int;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  INSERT INTO pitch_closures(pitch_id, starts_on, ends_on, reason, created_by)
  SELECT p.pitch_id, p_from, coalesce(p_to, p_from), nullif(trim(p_reason), ''), auth.uid()
    FROM pitch_closure_groups g JOIN pitches p ON p.pitch_id = ANY(g.pitch_ids) AND p.club_id = p_club
   WHERE g.group_id = p_group AND g.club_id = p_club;
  GET DIAGNOSTICS n = ROW_COUNT;
  IF n = 0 THEN RAISE EXCEPTION 'Group not found or has no pitches'; END IF;
  RETURN n;
END $$;

DO $$
DECLARE f text;
BEGIN
  FOREACH f IN ARRAY ARRAY['pitch_closure_groups_get(bigint)',
    'pitch_closure_group_save(bigint,bigint,text,bigint[])',
    'pitch_closure_group_delete(bigint,bigint)',
    'pitch_closure_group_close(bigint,bigint,date,date,text)'] LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION public.%s FROM PUBLIC, anon', f);
    EXECUTE format('GRANT EXECUTE ON FUNCTION public.%s TO authenticated', f);
  END LOOP;
END $$;

-- Clontarf: St Anne's (DCC) = the St Anne's pitches except 34 and 35.
INSERT INTO pitch_closure_groups(club_id, name, pitch_ids)
SELECT 1, 'St Anne''s (DCC)', array_agg(pitch_id ORDER BY pitch_id)
  FROM pitches
 WHERE club_id = 1 AND name IN ('Pitch 19','Pitch 21','Pitch 23','Pitch 23A','Pitch 30')
   AND NOT EXISTS (SELECT 1 FROM pitch_closure_groups WHERE club_id = 1 AND name = 'St Anne''s (DCC)')
HAVING count(*) > 0;
