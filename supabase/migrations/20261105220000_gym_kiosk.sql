-- Gym attendance kiosk (webviews/gym-kiosk/, edge function gym-kiosk).
--
-- Additive only: two new tables and one read-only view. Nothing existing is
-- altered. The RSVP table event_attendance is never written by the kiosk:
-- RSVP is intention, a check-in is what actually happened.
--
-- Both tables have RLS on and no policies, so the app's anon/authenticated
-- roles cannot read or write them. Only the gym-kiosk edge function (service
-- role) touches them.

-- ── Kiosk tablets ─────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.kiosk_devices (
    device_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamptz NOT NULL DEFAULT now(),
    club_id       bigint NOT NULL REFERENCES public.clubs (club_id),
    device_name   text NOT NULL,
    token_hash    text NOT NULL UNIQUE,          -- sha-256 of the tablet's secret token
    pin_hash      text NOT NULL,                 -- sha-256 of device_id + coach PIN
    paired_by     uuid,                          -- auth user of the coach who set it up
    last_seen_at  timestamptz,
    status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'unpaired'))
);

COMMENT ON TABLE public.kiosk_devices IS 'Gym kiosk tablets, one row per paired tablet. Written only by the gym-kiosk edge function.';

ALTER TABLE public.kiosk_devices ENABLE ROW LEVEL SECURITY;

-- ── Check-ins ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.event_checkins (
    checkin_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     timestamptz NOT NULL DEFAULT now(),       -- when the server received it
    client_uuid    uuid NOT NULL UNIQUE,                     -- made on the tablet; offline replays are no-ops
    event_id       bigint REFERENCES public.events (event_id),  -- NULL = Open gym (no event)
    club_id        bigint NOT NULL REFERENCES public.clubs (club_id),
    team_id        bigint REFERENCES public.teams (team_id),
    member_id      bigint NOT NULL REFERENCES public.members (member_id),
    checked_in_at  timestamptz NOT NULL,                     -- when the member tapped, by the tablet's clock
    checkin_date   date NOT NULL,                            -- checked_in_at as a Europe/Dublin date
    method         text NOT NULL CHECK (method IN ('tap', 'qr', 'coach')),
    device_id      bigint REFERENCES public.kiosk_devices (device_id),
    status         text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'undone')),
    undone_at      timestamptz
);

COMMENT ON TABLE public.event_checkins IS 'Gym kiosk check-ins: who actually turned up. Separate from event_attendance (RSVP). event_id NULL = Open gym.';

ALTER TABLE public.event_checkins ENABLE ROW LEVEL SECURITY;

-- One active check-in per member per event, and per club per day for Open gym.
CREATE UNIQUE INDEX IF NOT EXISTS event_checkins_one_per_event
    ON public.event_checkins (event_id, member_id)
    WHERE status = 'active' AND event_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS event_checkins_one_open_gym_per_day
    ON public.event_checkins (club_id, member_id, checkin_date)
    WHERE status = 'active' AND event_id IS NULL;

CREATE INDEX IF NOT EXISTS event_checkins_club_date ON public.event_checkins (club_id, checkin_date);
CREATE INDEX IF NOT EXISTS event_checkins_member    ON public.event_checkins (member_id);

-- ── Reporting view ────────────────────────────────────────────────────────
-- One row per active check-in, with the member's latest RSVP for that event.
-- walk_in = checked in to an event without an Accept (no reply or declined).
-- security_invoker: callers only see rows RLS lets them see (today: service
-- role and SQL editor only).
CREATE OR REPLACE VIEW public.view_event_checkins
WITH (security_invoker = true) AS
SELECT
    c.checkin_id,
    c.checkin_date,
    c.checked_in_at,
    c.club_id,
    c.team_id,
    c.event_id,
    e.event_title,
    e.event_date_time,
    e.squad_id,
    c.member_id,
    m.first_name,
    m.last_name,
    c.method,
    c.device_id,
    rsvp.response_id                                   AS rsvp_response_id,
    CASE WHEN c.event_id IS NULL THEN NULL WHEN rsvp.response_id = 3 THEN 'Accepted' WHEN rsvp.response_id = 4 THEN 'Declined' ELSE 'No response' END AS rsvp,
    (c.event_id IS NOT NULL AND rsvp.response_id IS DISTINCT FROM 3) AS walk_in,
    (c.event_id IS NULL)                               AS open_gym
FROM public.event_checkins c
JOIN public.members m ON m.member_id = c.member_id
LEFT JOIN public.events e ON e.event_id = c.event_id
LEFT JOIN LATERAL (
    SELECT a.response_id
    FROM public.event_attendance a
    WHERE a.event_id = c.event_id
      AND a.member_id = c.member_id
    ORDER BY a.created_at DESC, a.attendance_id DESC   -- latest reply wins, as in the app's RPCs
    LIMIT 1
) rsvp ON true
WHERE c.status = 'active';

COMMENT ON VIEW public.view_event_checkins IS 'Gym kiosk check-ins with RSVP and walk-in flag. Walk-in = checked in without an Accept.';

-- Keep the new objects away from the app's API roles; the edge function uses
-- the service role.
REVOKE ALL ON public.kiosk_devices       FROM anon, authenticated;
REVOKE ALL ON public.event_checkins      FROM anon, authenticated;
REVOKE ALL ON public.view_event_checkins FROM anon, authenticated;
