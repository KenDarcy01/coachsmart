-- The week as members see it.
CREATE OR REPLACE FUNCTION public.pitch_week_snapshot(p_club bigint, p_monday date)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
  SELECT jsonb_build_object(
    'week_start', p_monday,
    'pitches', coalesce((
      SELECT jsonb_agg(jsonb_build_object('pitch_id', p.pitch_id, 'name', p.name, 'venue', v.name,
               'surface', p.surface, 'split', p.split) ORDER BY v.sort, v.venue_id, p.sort, p.pitch_id)
        FROM pitches p JOIN pitch_venues v ON v.venue_id = p.venue_id
       WHERE p.club_id = p_club AND p.is_active AND v.is_active), '[]'::jsonb),
    'closures', coalesce((
      SELECT jsonb_agg(jsonb_build_object('pitch_id', c.pitch_id, 'starts_on', c.starts_on,
               'ends_on', c.ends_on, 'reason', c.reason))
        FROM pitch_closures c JOIN pitches p ON p.pitch_id = c.pitch_id
       WHERE p.club_id = p_club AND c.starts_on <= p_monday + 6 AND c.ends_on >= p_monday), '[]'::jsonb),
    'bookings', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
               'pitch_id', b.pitch_id, 'part', b.part,
               'starts_at', to_char(b.starts_at, 'YYYY-MM-DD"T"HH24:MI:SS'),
               'ends_at', to_char(b.ends_at, 'YYYY-MM-DD"T"HH24:MI:SS'),
               'kind', b.kind,
               'name', coalesce(g.name, nullif(b.title, ''),
                                public.pitch_group_label(t.team_name, c.club_name, extract(year FROM b.starts_at)::int)),
               'code', coalesce(g.code, ''), 'team_id', b.team_id,
               'opposition', e.opposition, 'referee', b.referee, 'dressing_rooms', b.dressing_rooms)
             ORDER BY b.starts_at)
        FROM pitch_bookings b
        JOIN clubs c ON c.club_id = b.club_id
        LEFT JOIN pitch_groups g ON g.group_id = b.group_id
        LEFT JOIN teams t ON t.team_id = b.team_id
        LEFT JOIN events e ON e.event_id = b.event_id
       WHERE b.club_id = p_club AND b.status = 'confirmed'
         AND b.starts_at >= p_monday::timestamp AND b.starts_at < p_monday::timestamp + interval '7 days'), '[]'::jsonb));
$$;

CREATE OR REPLACE FUNCTION public.pitch_publish_week(p_club bigint, p_monday date)
RETURNS timestamptz LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE v_week date := date_trunc('week', p_monday::timestamp)::date; v_at timestamptz := now();
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  INSERT INTO pitch_weeks(club_id, week_start, rolled_by, published_at, published_by, snapshot)
  VALUES (p_club, v_week, auth.uid(), v_at, auth.uid(), public.pitch_week_snapshot(p_club, v_week))
  ON CONFLICT (club_id, week_start) DO UPDATE
    SET published_at = v_at, published_by = auth.uid(),
        snapshot = public.pitch_week_snapshot(p_club, v_week);
  RETURN v_at;
END $$;

-- Publish state for the officer's board: when the week was published and
-- whether anything changed since.
CREATE OR REPLACE FUNCTION public.pitch_week_status(p_club bigint, p_monday date)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE w pitch_weeks%ROWTYPE; v_week date := date_trunc('week', p_monday::timestamp)::date;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  SELECT * INTO w FROM pitch_weeks WHERE club_id = p_club AND week_start = v_week;
  RETURN jsonb_build_object(
    'published_at', w.published_at,
    'changed', w.published_at IS NULL
               OR w.snapshot IS DISTINCT FROM public.pitch_week_snapshot(p_club, v_week));
END $$;

-- Clubs whose published pitch weeks the caller can read: any active member
-- of a team at the club, or an officer.
CREATE OR REPLACE FUNCTION public.pitch_member_clubs()
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'club_id', c.club_id, 'club_name', c.club_name, 'crest', c.crest,
           'primary_colour', c.primary_colour, 'secondary_colour', c.secondary_colour,
           'third_colour', c.third_colour,
           'officer', coalesce(public.is_club_officer(c.club_id), false)) ORDER BY c.club_name), '[]'::jsonb)
    FROM clubs c
   WHERE auth.uid() IS NOT NULL
     AND (c.club_id IN (SELECT t.club_id FROM teams t
                          JOIN member_team_link mtl ON mtl.team_id = t.team_id AND mtl.status = 'active'
                          JOIN members m ON m.member_id = mtl.member_id
                         WHERE m.user_id = auth.uid())
          OR coalesce(public.is_club_officer(c.club_id), false))
     AND EXISTS (SELECT 1 FROM pitch_weeks w WHERE w.club_id = c.club_id AND w.published_at IS NOT NULL);
$$;

CREATE OR REPLACE FUNCTION public.pitch_published_week(p_club bigint, p_monday date)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE w pitch_weeks%ROWTYPE; v_week date := date_trunc('week', p_monday::timestamp)::date;
BEGIN
  IF auth.uid() IS NULL OR NOT (
       coalesce(public.is_club_officer(p_club), false)
       OR EXISTS (SELECT 1 FROM teams t
                    JOIN member_team_link mtl ON mtl.team_id = t.team_id AND mtl.status = 'active'
                    JOIN members m ON m.member_id = mtl.member_id
                   WHERE m.user_id = auth.uid() AND t.club_id = p_club)) THEN
    RAISE EXCEPTION 'Only club members can see the pitch plan' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO w FROM pitch_weeks WHERE club_id = p_club AND week_start = v_week AND published_at IS NOT NULL;
  IF NOT FOUND THEN RETURN jsonb_build_object('week_start', v_week, 'published_at', NULL); END IF;
  RETURN w.snapshot || jsonb_build_object('published_at', w.published_at);
END $$;

-- Rolled copies and moved slots keep their group (redefined from part 1).
CREATE OR REPLACE FUNCTION public.pitch_apply_following(p_booking bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  src pitch_bookings%ROWTYPE;
  v_off interval;
  v_len interval;
  v_loc text;
  v_pin text;
BEGIN
  SELECT * INTO src FROM pitch_bookings WHERE booking_id = p_booking;
  IF NOT FOUND THEN RETURN; END IF;
  v_off := src.starts_at - date_trunc('week', src.starts_at);
  v_len := src.ends_at - src.starts_at;
  SELECT p.name || ', ' || v.name, v.location_pin INTO v_loc, v_pin
    FROM pitches p JOIN pitch_venues v ON v.venue_id = p.venue_id WHERE p.pitch_id = src.pitch_id;
  WITH RECURSIVE chain AS (
    SELECT booking_id FROM pitch_bookings WHERE rolled_from = p_booking
    UNION ALL
    SELECT c.booking_id FROM pitch_bookings c JOIN chain ON c.rolled_from = chain.booking_id)
  UPDATE pitch_bookings b
     SET pitch_id = src.pitch_id, part = src.part, status = src.status,
         starts_at = date_trunc('week', b.starts_at) + v_off,
         ends_at = date_trunc('week', b.starts_at) + v_off + v_len,
         title = src.title, team_id = src.team_id, group_id = src.group_id, note = src.note, updated_at = now()
    FROM chain
   WHERE b.booking_id = chain.booking_id;
  -- Linked events in those weeks show the new pitch.
  WITH RECURSIVE chain AS (
    SELECT booking_id FROM pitch_bookings WHERE rolled_from = p_booking
    UNION ALL
    SELECT c.booking_id FROM pitch_bookings c JOIN chain ON c.rolled_from = chain.booking_id)
  UPDATE events e SET location_name = v_loc, location_pin = coalesce(v_pin, e.location_pin)
    FROM pitch_bookings b JOIN chain ON chain.booking_id = b.booking_id
   WHERE e.event_id = b.event_id AND b.status = 'confirmed' AND v_loc IS NOT NULL;
  PERFORM public.pitch_unlink_moved(c.booking_id)
     FROM (WITH RECURSIVE chain AS (
             SELECT booking_id FROM pitch_bookings WHERE rolled_from = p_booking
             UNION ALL
             SELECT x.booking_id FROM pitch_bookings x JOIN chain ON x.rolled_from = chain.booking_id)
           SELECT booking_id FROM chain) c;
END $$;

CREATE OR REPLACE FUNCTION public.pitch_roll_week(p_club bigint, p_monday date)
RETURNS int LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  v_week timestamp := date_trunc('week', p_monday::timestamp);
  v_src  timestamp;
  v_n    int := 0;
  b      pitch_bookings%ROWTYPE;
  v_new  bigint;
  v_ev   bigint;
  v_loc  text;
  v_pin  text;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  -- Past weeks are history; only this week and later roll.
  IF v_week < date_trunc('week', (now() AT TIME ZONE 'Europe/Dublin')) THEN RETURN 0; END IF;
  IF EXISTS (SELECT 1 FROM pitch_weeks WHERE club_id = p_club AND week_start = v_week::date) THEN RETURN 0; END IF;

  SELECT max(date_trunc('week', starts_at)) INTO v_src
    FROM pitch_bookings
   WHERE club_id = p_club AND kind = 'training' AND status = 'confirmed'
     AND starts_at >= v_week - interval '8 weeks' AND starts_at < v_week;

  IF v_src IS NOT NULL THEN
    FOR b IN SELECT * FROM pitch_bookings
              WHERE club_id = p_club AND kind = 'training' AND status = 'confirmed'
                AND starts_at >= v_src AND starts_at < v_src + interval '1 week'
              ORDER BY starts_at
    LOOP
      -- Skip if the team (or name) already has this slot this week.
      CONTINUE WHEN EXISTS (
        SELECT 1 FROM pitch_bookings x
         WHERE x.club_id = p_club AND x.kind = 'training'
           AND x.starts_at = b.starts_at + (v_week - v_src)
           AND x.pitch_id IS NOT DISTINCT FROM b.pitch_id
           AND x.team_id IS NOT DISTINCT FROM b.team_id
           AND x.group_id IS NOT DISTINCT FROM b.group_id
           AND coalesce(x.title, '') = coalesce(b.title, ''));
      v_ev := NULL;
      IF b.team_id IS NOT NULL THEN
        SELECT e.event_id INTO v_ev
          FROM events e LEFT JOIN event_types et ON et.event_type_id = e.event_type_id
         WHERE e.team_id = b.team_id
           AND coalesce(et.event_type, 'Training') <> 'Match'
           AND coalesce(e.status, '') NOT ILIKE 'cancel%'
           AND abs(extract(epoch FROM (e.event_date_time AT TIME ZONE 'UTC') - (b.starts_at + (v_week - v_src)))) <= 2700
           AND NOT EXISTS (SELECT 1 FROM pitch_bookings y WHERE y.event_id = e.event_id)
         ORDER BY abs(extract(epoch FROM (e.event_date_time AT TIME ZONE 'UTC') - (b.starts_at + (v_week - v_src))))
         LIMIT 1;
      END IF;
      INSERT INTO pitch_bookings(club_id, pitch_id, part, starts_at, ends_at, kind, title, team_id,
                                 group_id, event_id, status, note, rolled_from, created_by)
      VALUES (p_club, b.pitch_id, b.part, b.starts_at + (v_week - v_src), b.ends_at + (v_week - v_src),
              'training', b.title, b.team_id, b.group_id, v_ev, 'confirmed', b.note, b.booking_id, auth.uid())
      RETURNING booking_id INTO v_new;
      IF v_ev IS NOT NULL THEN
        SELECT p.name || ', ' || v.name, v.location_pin INTO v_loc, v_pin
          FROM pitches p JOIN pitch_venues v ON v.venue_id = p.venue_id WHERE p.pitch_id = b.pitch_id;
        UPDATE pitch_bookings x SET prev_location = e.location_name, prev_pin = e.location_pin
          FROM events e WHERE x.booking_id = v_new AND e.event_id = v_ev;
        UPDATE events SET location_name = v_loc, location_pin = coalesce(v_pin, location_pin)
         WHERE event_id = v_ev;
      END IF;
      v_n := v_n + 1;
    END LOOP;
  END IF;

  INSERT INTO pitch_weeks(club_id, week_start, rolled_by, copied)
  VALUES (p_club, v_week::date, auth.uid(), v_n) ON CONFLICT DO NOTHING;
  RETURN v_n;
END $$;

