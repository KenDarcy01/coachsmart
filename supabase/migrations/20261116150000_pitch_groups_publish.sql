-- Pitch planner, part 2 (Ken, 2026-11-16):
--  * Groups: a placeholder for every team at the club, whether or not it
--    uses CoachSmart (U14 Boys, Nursery, All Stars, Social Ball...). A group
--    can be linked to a CoachSmart team; bookings belong to a group.
--  * Publish: when the officer has finished moving things, the week is
--    published as a snapshot that club members can read.
-- Additive only.

CREATE TABLE IF NOT EXISTS public.pitch_groups (
  group_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id    bigint NOT NULL REFERENCES public.clubs(club_id) ON DELETE CASCADE,
  name       text   NOT NULL,
  code       text   NOT NULL DEFAULT 'Other',
  team_id    bigint REFERENCES public.teams(team_id) ON DELETE SET NULL,
  -- How many training slots a week the group should get (0 = no target).
  sessions   smallint NOT NULL DEFAULT 0 CHECK (sessions BETWEEN 0 AND 14),
  sort       int NOT NULL DEFAULT 0,
  is_active  boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pitch_groups_club_idx ON public.pitch_groups(club_id);
CREATE UNIQUE INDEX IF NOT EXISTS pitch_groups_team_uq ON public.pitch_groups(team_id) WHERE team_id IS NOT NULL;
ALTER TABLE public.pitch_groups ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.pitch_bookings ADD COLUMN IF NOT EXISTS group_id bigint
  REFERENCES public.pitch_groups(group_id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS pitch_bookings_group_idx ON public.pitch_bookings(group_id) WHERE group_id IS NOT NULL;

ALTER TABLE public.pitch_weeks ADD COLUMN IF NOT EXISTS published_at timestamptz;
ALTER TABLE public.pitch_weeks ADD COLUMN IF NOT EXISTS published_by uuid;
ALTER TABLE public.pitch_weeks ADD COLUMN IF NOT EXISTS snapshot jsonb;

-- Age-group name for a CoachSmart team: "Clontarf Boys 2012" in 2026 -> "U14 Boys".
CREATE OR REPLACE FUNCTION public.pitch_group_label(p_team_name text, p_club_name text, p_year int)
RETURNS text LANGUAGE plpgsql IMMUTABLE SET search_path = 'public' AS $$
DECLARE
  y int := substring(p_team_name FROM '(?:19|20)[0-9]{2}')::int;
  rest text := p_team_name;
  w text;
BEGIN
  FOREACH w IN ARRAY string_to_array(coalesce(p_club_name, ''), ' ') LOOP
    IF length(w) > 2 AND lower(rest) LIKE lower(w) || '%' THEN
      rest := trim(substring(rest FROM length(w) + 1));
    END IF;
  END LOOP;
  IF y IS NULL THEN RETURN coalesce(nullif(rest, ''), p_team_name); END IF;
  rest := trim(regexp_replace(replace(rest, y::text, ''), '\s+', ' ', 'g'));
  RETURN trim('U' || (p_year - y) || ' ' || rest);
END $$;

-- Adds a group for every CoachSmart team at the club that has none yet.
CREATE OR REPLACE FUNCTION public.pitch_groups_sync(p_club bigint)
RETURNS int LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE n int;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  INSERT INTO pitch_groups(club_id, name, code, team_id, sessions, sort)
  SELECT t.club_id,
         public.pitch_group_label(t.team_name, c.club_name, extract(year FROM now())::int),
         CASE WHEN coalesce(t.team_female, false) THEN 'Ladies Football' ELSE 'Football' END,
         t.team_id, 2,
         1000 + row_number() OVER (ORDER BY t.team_name)
    FROM teams t JOIN clubs c ON c.club_id = t.club_id
   WHERE t.club_id = p_club
     AND t.team_name !~* 'test'
     AND NOT EXISTS (SELECT 1 FROM pitch_groups g WHERE g.team_id = t.team_id);
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;

CREATE OR REPLACE FUNCTION public.pitch_group_save(p_club bigint, p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  v_id bigint := nullif(p->>'group_id', '')::bigint;
  v_team bigint := nullif(p->>'team_id', '')::bigint;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  IF coalesce(trim(p->>'name'), '') = '' THEN RAISE EXCEPTION 'Give the group a name'; END IF;
  IF v_team IS NOT NULL AND NOT EXISTS (SELECT 1 FROM teams WHERE team_id = v_team AND club_id = p_club) THEN
    RAISE EXCEPTION 'Team not found';
  END IF;
  IF v_id IS NULL THEN
    INSERT INTO pitch_groups(club_id, name, code, team_id, sessions, sort)
    VALUES (p_club, trim(p->>'name'), coalesce(nullif(p->>'code', ''), 'Other'), v_team,
            coalesce((p->>'sessions')::smallint, 0),
            coalesce((p->>'sort')::int, (SELECT coalesce(max(sort), 0) + 1 FROM pitch_groups WHERE club_id = p_club)))
    RETURNING group_id INTO v_id;
  ELSE
    UPDATE pitch_groups SET name = trim(p->>'name'),
           code = coalesce(nullif(p->>'code', ''), code),
           team_id = CASE WHEN p ? 'team_id' THEN v_team ELSE team_id END,
           sessions = coalesce((p->>'sessions')::smallint, sessions),
           sort = coalesce((p->>'sort')::int, sort),
           is_active = coalesce((p->>'is_active')::boolean, is_active)
     WHERE group_id = v_id AND club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Group not found'; END IF;
    -- Bookings follow the group's team.
    UPDATE pitch_bookings SET team_id = (SELECT team_id FROM pitch_groups WHERE group_id = v_id)
     WHERE group_id = v_id AND event_id IS NULL;
  END IF;
  RETURN v_id;
END $$;

-- A booking for a group takes the group's team; a booking for a team
-- takes that team's group.
CREATE OR REPLACE FUNCTION public.pitch_bookings_group_fill()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
BEGIN
  IF NEW.group_id IS NOT NULL AND NEW.team_id IS NULL THEN
    SELECT team_id INTO NEW.team_id FROM pitch_groups WHERE group_id = NEW.group_id;
  ELSIF NEW.group_id IS NULL AND NEW.team_id IS NOT NULL THEN
    SELECT group_id INTO NEW.group_id FROM pitch_groups WHERE team_id = NEW.team_id;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS pitch_bookings_group_fill ON public.pitch_bookings;
CREATE TRIGGER pitch_bookings_group_fill BEFORE INSERT OR UPDATE OF group_id, team_id
  ON public.pitch_bookings FOR EACH ROW EXECUTE FUNCTION public.pitch_bookings_group_fill();

-- group_id on save: pitch_booking_save passes the whole jsonb, so set it
-- here after the save (keeps the first migration's function unchanged).
CREATE OR REPLACE FUNCTION public.pitch_booking_save_v2(p_club bigint, p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE
  v_id bigint;
  v_group bigint := nullif(p->>'group_id', '')::bigint;
  v_team bigint;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  IF v_group IS NOT NULL THEN
    SELECT team_id INTO v_team FROM pitch_groups WHERE group_id = v_group AND club_id = p_club;
    IF NOT FOUND THEN RAISE EXCEPTION 'Group not found'; END IF;
    p := p || jsonb_build_object('team_id', v_team);
  END IF;
  v_id := public.pitch_booking_save(p_club, p);
  IF p ? 'group_id' THEN
    UPDATE pitch_bookings SET group_id = v_group WHERE booking_id = v_id;
  END IF;
  -- Copies in later weeks follow the group too.
  IF coalesce((p->>'following')::boolean, true) AND p ? 'group_id' THEN
    WITH RECURSIVE chain AS (
      SELECT booking_id FROM pitch_bookings WHERE rolled_from = v_id
      UNION ALL
      SELECT c.booking_id FROM pitch_bookings c JOIN chain ON c.rolled_from = chain.booking_id)
    UPDATE pitch_bookings b SET group_id = v_group, team_id = v_team
      FROM chain WHERE b.booking_id = chain.booking_id AND b.event_id IS NULL;
  END IF;
  RETURN v_id;
END $$;

-- Groups for the board, with how many training slots each has that week.
CREATE OR REPLACE FUNCTION public.pitch_groups_get(p_club bigint, p_monday date)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'public' AS $$
DECLARE r jsonb;
BEGIN
  PERFORM public.pitch_require_admin(p_club);
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'group_id', g.group_id, 'name', g.name, 'code', g.code, 'team_id', g.team_id,
           'team_name', t.team_name, 'sessions', g.sessions, 'sort', g.sort,
           'booked', (SELECT count(*) FROM pitch_bookings b
                       WHERE b.group_id = g.group_id AND b.kind = 'training' AND b.status = 'confirmed'
                         AND b.starts_at >= p_monday::timestamp
                         AND b.starts_at < p_monday::timestamp + interval '7 days'))
         ORDER BY g.sort, g.name), '[]'::jsonb)
    INTO r
    FROM pitch_groups g LEFT JOIN teams t ON t.team_id = g.team_id
   WHERE g.club_id = p_club AND g.is_active;
  RETURN r;
END $$;

