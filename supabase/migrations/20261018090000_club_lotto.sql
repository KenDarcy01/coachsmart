-- One week used by each ticket in a draw. One-off tickets end when their weeks run
-- out, and so do stopped weekly tickets.
CREATE OR REPLACE FUNCTION public.lotto_use_week(p_ticket_ids bigint[])
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = 'public'
AS $$
  UPDATE public.lotto_tickets
  SET draws_entered = draws_entered + 1,
      status = CASE
                 WHEN draws_entered + 1 >= weeks_paid AND (plan = 'weeks' OR status = 'cancelled') THEN 'ended'
                 ELSE status
               END
  WHERE ticket_id = ANY (p_ticket_ids);
$$;
REVOKE ALL ON FUNCTION public.lotto_use_week(bigint[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.lotto_use_week(bigint[]) TO service_role;
