-- Club lotto (web first): a weekly pick-4 lotto per club, paid by card straight
-- into the club's own Stripe Connect account.
-- All reads and writes go through the `lotto` and `lotto-webhook` edge functions
-- with the service role, so RLS is on with no policies (no direct client access).

CREATE TABLE IF NOT EXISTS public.lotto_clubs (
  lotto_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id               bigint NOT NULL UNIQUE REFERENCES public.clubs(club_id),
  slug                  text   NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]{2,40}$'),
  lotto_name            text   NOT NULL DEFAULT 'Club Lotto',
  status                text   NOT NULL DEFAULT 'setup' CHECK (status IN ('setup', 'live', 'paused')),
  pool_size             int    NOT NULL DEFAULT 28  CHECK (pool_size BETWEEN 10 AND 60),
  pick_count            int    NOT NULL DEFAULT 4   CHECK (pick_count BETWEEN 3 AND 6),
  line_price_cents      int    NOT NULL DEFAULT 200 CHECK (line_price_cents >= 50),
  bundle_lines          int    NOT NULL DEFAULT 3   CHECK (bundle_lines BETWEEN 0 AND 10),
  bundle_price_cents    int    NOT NULL DEFAULT 500 CHECK (bundle_price_cents >= 0),
  draw_weekday          int    NOT NULL DEFAULT 2   CHECK (draw_weekday BETWEEN 0 AND 6), -- 0 = Sunday
  draw_time             time   NOT NULL DEFAULT '21:00',                                   -- Europe/Dublin
  sales_close_minutes   int    NOT NULL DEFAULT 180 CHECK (sales_close_minutes BETWEEN 0 AND 2880),
  jackpot_cents         int    NOT NULL DEFAULT 0   CHECK (jackpot_cents >= 0),
  jackpot_start_cents   int    NOT NULL DEFAULT 0   CHECK (jackpot_start_cents >= 0),
  rollover_cents        int    NOT NULL DEFAULT 0   CHECK (rollover_cents >= 0),
  match3_prize_cents    int    NOT NULL DEFAULT 0   CHECK (match3_prize_cents >= 0),
  lucky_dip_count       int    NOT NULL DEFAULT 0   CHECK (lucky_dip_count BETWEEN 0 AND 20),
  lucky_dip_prize_cents int    NOT NULL DEFAULT 0   CHECK (lucky_dip_prize_cents >= 0),
  licence_text          text,
  contact_email         text,
  colour_primary        text,
  colour_accent         text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.lotto_admins (
  lotto_id   bigint NOT NULL REFERENCES public.lotto_clubs(lotto_id) ON DELETE CASCADE,
  user_id    uuid   NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (lotto_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.lotto_players (
  player_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lotto_id   bigint NOT NULL REFERENCES public.lotto_clubs(lotto_id) ON DELETE CASCADE,
  email      text   NOT NULL,
  name       text   NOT NULL,
  phone      text,
  token      uuid   NOT NULL DEFAULT gen_random_uuid() UNIQUE,  -- private link for "your tickets" / stop weekly play
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS lotto_players_lotto_email ON public.lotto_players (lotto_id, lower(email));

-- One purchase. weeks_paid grows by one with each weekly renewal; each draw uses one week.
CREATE TABLE IF NOT EXISTS public.lotto_tickets (
  ticket_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lotto_id                   bigint NOT NULL REFERENCES public.lotto_clubs(lotto_id) ON DELETE CASCADE,
  player_id                  bigint NOT NULL REFERENCES public.lotto_players(player_id) ON DELETE CASCADE,
  lines                      jsonb  NOT NULL,                   -- [[3,11,17,25], ...]
  team_id                    bigint REFERENCES public.teams(team_id) ON DELETE SET NULL,
  plan                       text   NOT NULL CHECK (plan IN ('weeks', 'weekly')),
  weeks_bought               int    NOT NULL DEFAULT 1,
  price_cents                int    NOT NULL,                   -- per week
  weeks_paid                 int    NOT NULL DEFAULT 0,
  draws_entered              int    NOT NULL DEFAULT 0,
  status                     text   NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'cancelled', 'ended')),
  stripe_checkout_session_id text UNIQUE,
  stripe_subscription_id     text UNIQUE,
  agreed_18_at               timestamptz,
  created_at                 timestamptz NOT NULL DEFAULT now(),
  paid_at                    timestamptz,
  cancelled_at               timestamptz
);
CREATE INDEX IF NOT EXISTS lotto_tickets_lotto_status ON public.lotto_tickets (lotto_id, status);
CREATE INDEX IF NOT EXISTS lotto_tickets_player ON public.lotto_tickets (player_id);

CREATE TABLE IF NOT EXISTS public.lotto_payments (
  payment_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lotto_id     bigint NOT NULL REFERENCES public.lotto_clubs(lotto_id) ON DELETE CASCADE,
  ticket_id    bigint NOT NULL REFERENCES public.lotto_tickets(ticket_id) ON DELETE CASCADE,
  amount_cents int    NOT NULL,
  kind         text   NOT NULL CHECK (kind IN ('checkout', 'renewal')),
  stripe_ref   text   NOT NULL UNIQUE,  -- checkout session id or invoice id
  paid_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS lotto_payments_lotto_paid ON public.lotto_payments (lotto_id, paid_at);

CREATE TABLE IF NOT EXISTS public.lotto_draws (
  draw_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lotto_id           bigint NOT NULL REFERENCES public.lotto_clubs(lotto_id) ON DELETE CASCADE,
  draw_at            timestamptz NOT NULL,
  sales_close_at     timestamptz NOT NULL,
  status             text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'published')),
  numbers            int[],
  jackpot_cents      int,
  jackpot_won        boolean,
  next_jackpot_cents int,
  totals             jsonb,
  published_at       timestamptz,
  published_by       uuid,
  UNIQUE (lotto_id, draw_at)
);

CREATE TABLE IF NOT EXISTS public.lotto_entries (
  entry_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draw_id   bigint NOT NULL REFERENCES public.lotto_draws(draw_id) ON DELETE CASCADE,
  ticket_id bigint NOT NULL REFERENCES public.lotto_tickets(ticket_id) ON DELETE CASCADE,
  player_id bigint NOT NULL REFERENCES public.lotto_players(player_id) ON DELETE CASCADE,
  line_no   int    NOT NULL,
  numbers   int[]  NOT NULL,
  matches   int    NOT NULL,
  UNIQUE (draw_id, ticket_id, line_no)
);
CREATE INDEX IF NOT EXISTS lotto_entries_player ON public.lotto_entries (player_id);

CREATE TABLE IF NOT EXISTS public.lotto_winners (
  winner_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draw_id      bigint NOT NULL REFERENCES public.lotto_draws(draw_id) ON DELETE CASCADE,
  player_id    bigint NOT NULL REFERENCES public.lotto_players(player_id) ON DELETE CASCADE,
  ticket_id    bigint REFERENCES public.lotto_tickets(ticket_id) ON DELETE SET NULL,
  kind         text   NOT NULL CHECK (kind IN ('jackpot', 'match3', 'lucky_dip')),
  prize_cents  int    NOT NULL,
  display_name text   NOT NULL
);

