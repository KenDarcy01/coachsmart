-- Score keeper v2 (webviews/score-keeper.html)
--
-- The new score keeper saves every action on the phone first and uploads
-- them in batches. Each action carries a client-made id (client_id) so a
-- retried upload never creates a duplicate. It also records who scored
-- (member_id), half/full-time score corrections, and substitutions.
--
-- Nothing here changes how the current match-timer.html works: its rows get
-- kind = 'score', count = 1 and no client_id, exactly as before.

-- ── 1. match_stats_details: client id, player, kind ──────────────────────────
ALTER TABLE public.match_stats_details
  ADD COLUMN IF NOT EXISTS client_id uuid,
  ADD COLUMN IF NOT EXISTS member_id bigint REFERENCES public.members(member_id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'score';

ALTER TABLE public.match_stats_details
  DROP CONSTRAINT IF EXISTS match_stats_details_kind_check;
ALTER TABLE public.match_stats_details
  ADD CONSTRAINT match_stats_details_kind_check CHECK (kind IN ('score', 'correction'));

CREATE UNIQUE INDEX IF NOT EXISTS match_stats_details_client_id_key
  ON public.match_stats_details (client_id);

-- ── 2. match_subs ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.match_subs (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_stats_id bigint NOT NULL REFERENCES public.match_stats(id) ON DELETE CASCADE,
  client_id      uuid UNIQUE,
  half           int NOT NULL DEFAULT 1,
  event_second   int NOT NULL DEFAULT 0,
  member_off     bigint REFERENCES public.members(member_id) ON DELETE SET NULL,
  member_on      bigint REFERENCES public.members(member_id) ON DELETE SET NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS match_subs_match_stats_id_idx ON public.match_subs (match_stats_id);

-- Read and written only through the SECURITY DEFINER functions below.
ALTER TABLE public.match_subs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.match_subs FROM anon, authenticated;

-- ── 3. Helper: is the caller a member of the event's team? ───────────────────
CREATE OR REPLACE FUNCTION public.sk_is_team_member(p_team_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = 'public'
AS $$
  SELECT EXISTS (
    SELECT 1
      FROM public.user_member_link uml
      JOIN public.member_team_link mtl ON mtl.member_id = uml.member_id
     WHERE uml.user_id = auth.uid()
       AND mtl.team_id = p_team_id
       AND mtl.status  = 'active'
  );
$$;
REVOKE ALL ON FUNCTION public.sk_is_team_member(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.sk_is_team_member(bigint) TO authenticated;

-- ── 4. get_score_keeper_state ─────────────────────────────────────────────────
-- Everything the score keeper needs to open a match, in one call:
-- event, club colours, timer, the caller's session (active, else the latest
-- finalised one), score types, saved actions, subs, line-up and squad names.
CREATE OR REPLACE FUNCTION public.get_score_keeper_state(p_event_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = 'public'
AS $$
DECLARE
  v_uid       uuid := auth.uid();
  v_team_id   bigint;
  v_member    boolean;
  v_session   public.match_stats%ROWTYPE;
  v_squad_id  bigint;
  v_result    jsonb;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('error', 'not_signed_in');
  END IF;

  SELECT e.team_id INTO v_team_id FROM public.events e WHERE e.event_id = p_event_id;
  IF v_team_id IS NULL THEN
    RETURN jsonb_build_object('error', 'event_not_found');
  END IF;

  v_member := public.sk_is_team_member(v_team_id);

  -- The caller's active session, else their most recent finalised one
  SELECT * INTO v_session
    FROM public.match_stats ms
   WHERE ms.event_id = p_event_id AND ms.user_id = v_uid AND ms.status IN ('active', 'finalised')
   ORDER BY (ms.status = 'active') DESC, ms.id DESC
   LIMIT 1;

  SELECT mt.squad_id INTO v_squad_id
    FROM public.match_timer mt
   WHERE mt.event_id = p_event_id AND mt.user_id = v_uid;
  v_squad_id := COALESCE(v_session.squad_id, v_squad_id);

  SELECT jsonb_build_object(
    'event', (
      SELECT jsonb_build_object(
        'event_id',        e.event_id,
        'event_date_time', e.event_date_time,
        'event_title',     e.event_title,
        'opposition',      e.opposition,
        'team_id',         e.team_id,
        'team_name',       t.team_name,
        'club_name',       c.club_name,
        'primary_colour',  c.primary_colour,
        'secondary_colour',c.secondary_colour,
        'event_code',      ec.event_code,
        'event_type',      et.event_type
      )
      FROM public.events e
      LEFT JOIN public.teams t        ON t.team_id = e.team_id
      LEFT JOIN public.clubs c        ON c.club_id = t.club_id
      LEFT JOIN public.event_codes ec ON ec.code_id = e.event_code_id
      LEFT JOIN public.event_types et ON et.event_type_id = e.event_type_id
      WHERE e.event_id = p_event_id
    ),
    'is_member', v_member,
    'timer', (
      SELECT to_jsonb(mt) - 'user_id'
        FROM public.match_timer mt
       WHERE mt.event_id = p_event_id AND mt.user_id = v_uid
    ),
    'session', CASE WHEN v_session.id IS NULL THEN NULL ELSE jsonb_build_object(
      'id',           v_session.id,
      'status',       v_session.status,
      'opposition',   v_session.opposition,
      'squad_id',     v_session.squad_id,
      'finalised_at', v_session.finalised_at
    ) END,
    'squads', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('squad_id', s.squad_id, 'squad_name', s.squad_name)
                       ORDER BY s.squad_list_seq NULLS LAST, s.squad_name)
        FROM public.squads s WHERE s.team_id = v_team_id
    ), '[]'::jsonb),
    'score_types', COALESCE((
      WITH linked AS (
        SELECT mst.*
          FROM public.match_stat_type_team_link l
          JOIN public.match_stat_types mst ON mst.id = l.match_score_type_id
         WHERE l.team_id = v_team_id AND l.status IS TRUE AND mst.status IS TRUE
      ), chosen AS (
        SELECT * FROM linked
        UNION ALL
        SELECT mst.* FROM public.match_stat_types mst
         WHERE mst.status IS TRUE AND NOT EXISTS (SELECT 1 FROM linked)
      )
      SELECT jsonb_agg(jsonb_build_object(
               'id',               ch.id,
               'score_type',       ch.score_type,
               'abbreviated_name', ch.abbreviated_name,
               'score_value',      ch.score_value,
               'category',         COALESCE(cat.score_category, 'other')
             ) ORDER BY ch.score_category NULLS LAST, ch.score_value DESC NULLS LAST, ch.id)
        FROM chosen ch
        LEFT JOIN public.match_stat_categories cat ON cat.id = ch.score_category
    ), '[]'::jsonb),
    'actions', CASE WHEN v_session.id IS NULL THEN '[]'::jsonb ELSE COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
               'id',          COALESCE(d.client_id::text, 'srv-' || d.id),
               'kind',        d.kind,
               'score_type',  d.score_type,
               'side',        d.side,
               'count',       COALESCE(d.count, 1),
               'second',      d.event_second,
               'half',        d.half,
               'member_id',   d.member_id,
               'created_at',  d.created_at
             ) ORDER BY d.half, d.event_second, d.created_at)
        FROM public.match_stats_details d
       WHERE d.match_stats_id = v_session.id
    ), '[]'::jsonb) END,
    'subs', CASE WHEN v_session.id IS NULL THEN '[]'::jsonb ELSE COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
               'id',         COALESCE(s.client_id::text, 'srv-' || s.id),
               'half',       s.half,
               'second',     s.event_second,
               'member_off', s.member_off,
               'member_on',  s.member_on
             ) ORDER BY s.half, s.event_second, s.created_at)
        FROM public.match_subs s
       WHERE s.match_stats_id = v_session.id
    ), '[]'::jsonb) END,
    -- Latest saved line-up from the team selector (for this squad if one is set)
    'lineup', CASE WHEN NOT v_member THEN NULL ELSE (
      SELECT jsonb_build_object(
        'lineup_id', l.lineup_id,
        'format',    l.format,
        'squad_id',  l.squad_id,
        'players', COALESCE((
          SELECT jsonb_agg(jsonb_build_object(
                   'member_id', ld.member_id,
                   'number',    CASE WHEN ld.is_sub THEN l.format + ld.position_num ELSE ld.position_num END,
                   'position',  ld.position_label,
                   'is_sub',    ld.is_sub,
                   'first_name',m.first_name,
                   'last_name', m.last_name
                 ) ORDER BY ld.is_sub, ld.position_num)
            FROM public.lineup_details ld
            JOIN public.members m ON m.member_id = ld.member_id
           WHERE ld.lineup_id = l.lineup_id
        ), '[]'::jsonb)
      )
        FROM public.lineup l
       WHERE l.event_id = p_event_id AND l.team_id = v_team_id
         AND (v_squad_id IS NULL OR l.squad_id = v_squad_id OR l.squad_id IS NULL)
       ORDER BY (l.squad_id IS NOT DISTINCT FROM v_squad_id) DESC, l.lineup_id DESC
       LIMIT 1
    ) END,
    -- Everyone on the team's player list, for naming scorers without a line-up
    'players', CASE WHEN NOT v_member THEN '[]'::jsonb ELSE COALESCE((
      SELECT jsonb_agg(DISTINCT jsonb_build_object(
               'member_id',  m.member_id,
               'first_name', m.first_name,
               'last_name',  m.last_name
             ))
        FROM public.member_team_link mtl
        JOIN public.members m ON m.member_id = mtl.member_id
        JOIN public.member_team_role_link mtrl ON mtrl.member_team_id = mtl.member_team_id
        JOIN public.roles r ON r.role_id = mtrl.role_id
       WHERE mtl.team_id = v_team_id AND mtl.status = 'active' AND r.role_level = 10
    ), '[]'::jsonb) END
  ) INTO v_result;

  RETURN v_result;
END;
$$;
REVOKE ALL ON FUNCTION public.get_score_keeper_state(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_score_keeper_state(bigint) TO authenticated;

-- ── 5. sync_match_actions ─────────────────────────────────────────────────────
-- Applies a batch of actions from the phone, in order. Safe to resend: an
-- action whose client id is already stored is skipped. Returns the ids that
-- are now stored (or removed), so the phone can clear them from its outbox.
--
-- Action shapes (all carry "id", a uuid made on the phone):
--   {type:'score',      id, score_type, side, second, half, timer_status, member_id}
--   {type:'correction', id, score_type, side, count, second, half}
--   {type:'edit',       id, target, score_type, side, member_id}   (fields optional)
--   {type:'remove',     id, target}
--   {type:'sub',        id, second, half, member_off, member_on}
--   {type:'remove_sub', id, target}
-- p_timer, when given, is the phone's latest clock state for match_timer.
CREATE OR REPLACE FUNCTION public.sync_match_actions(
  p_match_stats_id bigint,
  p_actions        jsonb,
  p_timer          jsonb DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'public'
AS $$
DECLARE
  v_uid     uuid := auth.uid();
  v_event   bigint;
  v_team    bigint;
  a         jsonb;
  v_id      uuid;
  v_target  uuid;
  v_row     bigint;
  v_member  bigint;
  v_done    jsonb := '[]'::jsonb;
BEGIN
  SELECT ms.event_id, e.team_id INTO v_event, v_team
    FROM public.match_stats ms
    JOIN public.events e ON e.event_id = ms.event_id
   WHERE ms.id = p_match_stats_id AND ms.user_id = v_uid;
  IF v_event IS NULL THEN
    RAISE EXCEPTION 'Unauthorized' USING ERRCODE = '42501';
  END IF;

  FOR a IN SELECT * FROM jsonb_array_elements(COALESCE(p_actions, '[]'::jsonb)) LOOP
    v_id := (a->>'id')::uuid;
    -- A target is the phone's id for the row, or 'srv-<id>' for rows saved
    -- without one (older score keeper)
    v_target := CASE WHEN a->>'target' ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
                     THEN (a->>'target')::uuid END;
    v_row    := CASE WHEN a->>'target' ~ '^srv-[0-9]+$' THEN substring(a->>'target' FROM 5)::bigint END;

    -- Only keep a player id that belongs to this team
    v_member := NULLIF(a->>'member_id', '')::bigint;
    IF v_member IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.member_team_link mtl
       WHERE mtl.member_id = v_member AND mtl.team_id = v_team
    ) THEN
      v_member := NULL;
    END IF;

    CASE a->>'type'
      WHEN 'score', 'correction' THEN
        INSERT INTO public.match_stats_details (
          match_stats_id, score_type, side, count, event_second, timer_status, half,
          client_id, member_id, kind
        ) VALUES (
          p_match_stats_id,
          (a->>'score_type')::bigint,
          a->>'side',
          CASE WHEN a->>'type' = 'correction' THEN COALESCE((a->>'count')::smallint, 0) ELSE 1 END,
          LEAST(GREATEST(COALESCE((a->>'second')::int, 0), 0), 32767)::smallint,
          CASE WHEN a->>'timer_status' IN ('running', 'paused', 'stopped') THEN a->>'timer_status' ELSE 'paused' END,
          COALESCE((a->>'half')::int, 1),
          v_id,
          v_member,
          a->>'type'
        )
        ON CONFLICT (client_id) DO NOTHING;

      WHEN 'edit' THEN
        UPDATE public.match_stats_details d
           SET score_type = COALESCE((a->>'score_type')::bigint, d.score_type),
               side       = COALESCE(a->>'side', d.side),
               member_id  = CASE WHEN a ? 'member_id' THEN v_member ELSE d.member_id END
         WHERE d.match_stats_id = p_match_stats_id AND (d.client_id = v_target OR d.id = v_row);

      WHEN 'remove' THEN
        DELETE FROM public.match_stats_details d
         WHERE d.match_stats_id = p_match_stats_id AND (d.client_id = v_target OR d.id = v_row);

      WHEN 'sub' THEN
        INSERT INTO public.match_subs (match_stats_id, client_id, half, event_second, member_off, member_on)
        VALUES (
          p_match_stats_id, v_id,
          COALESCE((a->>'half')::int, 1),
          GREATEST(COALESCE((a->>'second')::int, 0), 0),
          (SELECT mtl.member_id FROM public.member_team_link mtl
            WHERE mtl.member_id = NULLIF(a->>'member_off', '')::bigint AND mtl.team_id = v_team LIMIT 1),
          (SELECT mtl.member_id FROM public.member_team_link mtl
            WHERE mtl.member_id = NULLIF(a->>'member_on', '')::bigint AND mtl.team_id = v_team LIMIT 1)
        )
        ON CONFLICT (client_id) DO NOTHING;

      WHEN 'remove_sub' THEN
        DELETE FROM public.match_subs s
         WHERE s.match_stats_id = p_match_stats_id AND (s.client_id = v_target OR s.id = v_row);

      ELSE
        NULL;  -- unknown action types are acknowledged and dropped
    END CASE;

    v_done := v_done || to_jsonb(v_id::text);
  END LOOP;

  IF p_timer IS NOT NULL THEN
    UPDATE public.match_timer mt
       SET status           = CASE WHEN p_timer->>'status' IN ('running', 'paused') THEN p_timer->>'status' ELSE mt.status END,
           started_at       = NULLIF(p_timer->>'started_at', '')::timestamptz,
           elapsed_seconds  = COALESCE((p_timer->>'elapsed_seconds')::int, mt.elapsed_seconds),
           current_half     = COALESCE((p_timer->>'current_half')::int, mt.current_half),
           duration_seconds = COALESCE((p_timer->>'duration_seconds')::int, mt.duration_seconds),
           injury_seconds   = COALESCE((p_timer->>'injury_seconds')::int, mt.injury_seconds)
     WHERE mt.event_id = v_event AND mt.user_id = v_uid;
  END IF;

  RETURN jsonb_build_object('done', v_done);
END;
$$;
REVOKE ALL ON FUNCTION public.sync_match_actions(bigint, jsonb, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.sync_match_actions(bigint, jsonb, jsonb) TO authenticated;

-- ── 6. get_match_stats_session: add player, kind, count and subs ─────────────
-- Same shape as before plus extra fields, so the current chart keeps working.
CREATE OR REPLACE FUNCTION public.get_match_stats_session(p_match_stats_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'public'
AS $$
DECLARE
    v_event_id    bigint;
    v_owner_id    uuid;
    v_opposition  text;
    v_title       text;
    v_finalised   timestamptz;
    v_timer       jsonb;
    v_team_name   text;
    v_member      boolean;
BEGIN
    IF auth.uid() IS NULL THEN
        RETURN '{}'::jsonb;
    END IF;

    SELECT ms.event_id, ms.user_id, ms.opposition, e.event_title, ms.finalised_at, t.team_name,
           public.sk_is_team_member(e.team_id)
      INTO v_event_id, v_owner_id, v_opposition, v_title, v_finalised, v_team_name, v_member
      FROM public.match_stats ms
      JOIN public.events      e ON e.event_id = ms.event_id
      LEFT JOIN public.teams  t ON t.team_id  = e.team_id
     WHERE ms.id = p_match_stats_id;

    IF v_event_id IS NULL THEN
        RETURN '{}'::jsonb;
    END IF;

    SELECT jsonb_build_object(
               'elapsed_seconds',  COALESCE(mt.elapsed_seconds, 0),
               'started_at',       mt.started_at,
               'status',           COALESCE(mt.status, 'paused'),
               'duration_seconds', COALESCE(mt.duration_seconds, 1800),
               'current_half',     COALESCE(mt.current_half, 1)
           )
      INTO v_timer
      FROM public.match_timer mt
     WHERE mt.event_id = v_event_id
       AND mt.user_id  = v_owner_id;

    RETURN jsonb_build_object(
        'match_stats_id', p_match_stats_id,
        'event_id',       v_event_id,
        'team_name',      v_team_name,
        'opposition',     COALESCE(v_opposition, 'Opposition'),
        'event_title',    COALESCE(v_title, 'Match'),
        'finalised_at',   v_finalised,
        'timer',          COALESCE(v_timer,
                              '{"elapsed_seconds":0,"status":"paused","duration_seconds":1800,"current_half":1}'::jsonb),
        'events', COALESCE((
            SELECT jsonb_agg(
                jsonb_build_object(
                    'id',               msd.id,
                    'half',             msd.half,
                    'second',           msd.event_second,
                    'side',             msd.side,
                    'score_value',      mst.score_value,
                    'abbreviated_name', mst.abbreviated_name,
                    'score_type_name',  mst.score_type,
                    'kind',             msd.kind,
                    'count',            COALESCE(msd.count, 1),
                    'member_id',        msd.member_id,
                    'member_name',      CASE WHEN v_member THEN TRIM(CONCAT(m.first_name, ' ', m.last_name)) END,
                    'created_at',       msd.created_at
                )
                ORDER BY msd.half, msd.event_second, msd.created_at
            )
            FROM public.match_stats_details msd
            JOIN public.match_stat_types    mst ON mst.id = msd.score_type
            LEFT JOIN public.members        m   ON m.member_id = msd.member_id
            WHERE msd.match_stats_id = p_match_stats_id
        ), '[]'::jsonb),
        'subs', COALESCE((
            SELECT jsonb_agg(
                jsonb_build_object(
                    'half',     s.half,
                    'second',   s.event_second,
                    'off_name', CASE WHEN v_member THEN TRIM(CONCAT(moff.first_name, ' ', moff.last_name)) END,
                    'on_name',  CASE WHEN v_member THEN TRIM(CONCAT(mon.first_name, ' ', mon.last_name)) END
                )
                ORDER BY s.half, s.event_second, s.created_at
            )
            FROM public.match_subs s
            LEFT JOIN public.members moff ON moff.member_id = s.member_off
            LEFT JOIN public.members mon  ON mon.member_id  = s.member_on
            WHERE s.match_stats_id = p_match_stats_id
        ), '[]'::jsonb)
    );
END;
$$;
GRANT EXECUTE ON FUNCTION public.get_match_stats_session(bigint) TO authenticated;
